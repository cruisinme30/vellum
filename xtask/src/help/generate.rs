//! Derived files: corpus inputs and the embedded page table.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use super::CORPUS_DIR;
use super::book::Book;
use super::examples::Example;

/// One corpus input per example: `corpus/guide/<kind>/<name>.md`.
#[must_use]
pub fn corpus(examples: &[Example]) -> BTreeMap<PathBuf, String> {
    examples
        .iter()
        .map(|e| {
            let path = PathBuf::from(format!("{CORPUS_DIR}/{}.md", e.name));
            let mut body = e.body.trim_end().to_owned();
            body.push('\n');
            (path, body)
        })
        .collect()
}

/// The Rust variant for a book name.
fn variant(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_uppercase().chain(chars).collect()
    })
}

/// `crates/vellum-help/src/pages.rs`: every page, summary, asset and help
/// anchor, embedded with `include_str!` and `include_bytes!`.
#[must_use]
pub fn page_table(books: &[Book], anchors: &[(String, String)]) -> String {
    // The header is split so licence scanners do not read this source
    // line as a declaration with a trailing escape.
    let mut out = String::from(concat!(
        "// SPDX-FileCopyrightText: 2026 The Vellum contributors\n",
        "// SPDX-License-",
        "Identifier: AGPL-3.0-only\n",
    ));
    out.push_str(
        "\n\
         // @generated by `cargo xtask help write` from docs/. Do not edit.\n\
         \n\
         use crate::{Asset, Book, Page};\n\
         \n\
         /// Every page of every book, in `SUMMARY.md` order.\n\
         pub static PAGES: &[Page] = &[\n",
    );
    for book in books {
        let variant = variant(&book.name);
        for page in &book.pages {
            let front = page.front.clone().unwrap_or_default();
            let _ = writeln!(
                out,
                "    Page {{\n        book: Book::{variant},\n        path: {:?},\n        id: {:?},\n        title: {:?},\n        markdown: include_str!(\"../../../docs/{}.book/{}\"),\n    }},",
                page.path,
                front.id.unwrap_or_default(),
                front.title.unwrap_or_default(),
                book.name,
                page.path,
            );
        }
    }
    out.push_str(
        "];\n\n/// Each book's `SUMMARY.md`.\npub static SUMMARIES: &[(Book, &str)] = &[\n",
    );
    for book in books {
        let _ = writeln!(
            out,
            "    (\n        Book::{},\n        include_str!(\"../../../docs/{}.book/SUMMARY.md\"),\n    ),",
            variant(&book.name),
            book.name
        );
    }
    out.push_str(
        "];\n\n/// Images and other files the pages refer to.\npub static ASSETS: &[Asset] = &[\n",
    );
    for book in books {
        for asset in &book.assets {
            let _ = writeln!(
                out,
                "    Asset {{\n        book: Book::{},\n        path: {asset:?},\n        bytes: include_bytes!(\"../../../docs/{}.book/{asset}\"),\n    }},",
                variant(&book.name),
                book.name,
            );
        }
    }
    out.push_str("];\n\n/// Contextual help IDs and their `book/page#anchor` targets.\npub static ANCHORS: &[(&str, &str)] = &[\n");
    for (id, target) in anchors {
        let _ = writeln!(out, "    ({id:?}, {target:?}),");
    }
    out.push_str("];\n");
    out
}
